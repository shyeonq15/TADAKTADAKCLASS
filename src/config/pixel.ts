/** 그림이 올바른지: 16줄, 줄마다 16칸, 쓸 수 있는 숫자만 */
export function validPixelRows(rows: unknown, bits: 1 | 2): rows is string[] {
  const allowed = bits === 1 ? /^[01]{16}$/ : /^[0-3]{16}$/;
  return Array.isArray(rows) && rows.length === PIXEL_SIZE && rows.every((r) => typeof r === "string" && allowed.test(r));
}
